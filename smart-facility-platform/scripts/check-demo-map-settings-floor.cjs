const fs = require('node:fs');
const path = require('node:path');
let source = fs.readFileSync(path.join(__dirname, 'check-demo-map-m2.cjs'), 'utf8');
const start = source.indexOf('    // --- Map settings:');
const end = source.indexOf('    publishEvidence();', start);
if (start < 0 || end < 0) throw new Error('M2 harness changed');
const scenario = `
    const find = condition => "(() => {const walk=vm=>vm && ("+condition+" ? vm : (vm.$children||[]).map(walk).find(Boolean));return walk(document.querySelector('#app').__vue__);})()";
    const mapSet = find('vm.handleRoomList && vm.handleGetFloorList && vm.$refs && vm.$refs.CreateFloor');
    const floorEditor = find('vm.place && vm.candidates && vm.exit && vm.$el.getBoundingClientRect().width>0');
    await evaluate("location.hash='#/ms/mapSet'");
    await waitPage("!!document.querySelector('.map-set') && !!("+mapSet+")", 'map set');
    await evaluate(mapSet+".handleTableData(2,920001,'演示一号楼')");
    await waitPage(mapSet+" && !"+mapSet+".loading && "+mapSet+".building.some(row=>row.id===930001 && row.mapUrl==='demo-floor-a-1f')", 'floor list');
    const floors = await evaluate(mapSet+".building.map(row=>({id:row.id,name:row.name,mapUrl:row.mapUrl,mapId:row.mapId}))");
    assert.ok(floors.find(row => row.id === 930001 && row.mapUrl === 'demo-floor-a-1f'));
    assert.equal(floors.find(row => row.id === 930002).mapUrl, '');
    const bodyText = await evaluate("document.body.innerText");
    assert.equal(bodyText.includes('配置房间'), true);
    assert.equal(bodyText.includes('未设置'), true);
    const disabled = await evaluate("!!document.querySelector('.map-floor-config.is-disabled')");
    assert.equal(disabled, true, 'empty floor config disabled');
    await screenshot('01-floor-list');
    await evaluate(mapSet+".handleConfiguration({id:930002,name:'2F',mapUrl:'',mapId:940002},2)");
    assert.equal(await evaluate("location.hash.includes('/ms/mapSet')"), true, 'no map stays on map set');
    await evaluate(mapSet+".handleConfiguration({id:930001,name:'1F',mapUrl:'demo-floor-a-1f',mapId:940001},2)");
    await waitPage("location.hash.includes('/floor/designer') && location.hash.includes('930001')", 'floor designer');
    await waitPage("!!("+floorEditor+") && !"+floorEditor+".loading", 'floor editor ready');
    const placed = await evaluate(floorEditor+".placed.map(row=>row.id).sort()");
    assert.deepEqual(placed, [950001, 950002, 950003]);
    await screenshot('02-floor-designer');
    await evaluate(floorEditor+".exit()");
    await waitPage("location.hash.includes('/floor/view') && location.hash.includes('930001')", 'floor preview');
    await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    const leftover = await evaluate("(() => {const mapSet = document.querySelector('.map-set'); const configs = Array.from(document.querySelectorAll('.map-floor-config')); return {mapSetDisplay: mapSet ? getComputedStyle(mapSet).display : 'none', visibleConfig: configs.filter(node => node.offsetParent).length};})()");
    assert.equal(leftover.mapSetDisplay, 'none', 'map settings not stacked');
    assert.equal(leftover.visibleConfig, 0, 'floor config buttons not stacked');
    const toolbar = await evaluate("(() => {const icon = document.querySelector('.unfolder'); const btn = document.querySelector('.type-button'); if (!icon || !btn) return null; const a = icon.getBoundingClientRect(); const b = btn.getBoundingClientRect(); return {delta: Math.abs((a.top + a.height / 2) - (b.top + b.height / 2)), hasLayoutBtn: document.body.innerText.includes('查看设备布局')};})()");
    assert.ok(toolbar && toolbar.delta <= 2, 'folder icon vertically centered');
    assert.equal(toolbar.hasLayoutBtn, false);
    await screenshot('03-floor-preview');
    const newFloorId = 930001;
`;
source = source.slice(0, start) + scenario + source.slice(end);
source = source.replaceAll('map-m2', 'map-settings-floor');
new Function('require', '__dirname', source)(require, __dirname);
