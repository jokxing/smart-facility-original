// Reuse local-only browser launch/login/evidence harness.
const fs = require('node:fs');
const path = require('node:path');
let source = fs.readFileSync(path.join(__dirname, 'check-demo-map-m2.cjs'), 'utf8');
const start = source.indexOf('    // --- Map settings:');
const end = source.indexOf('    publishEvidence();', start);
if (start < 0 || end < 0) throw new Error('M2 harness changed');
const scenario = `
    const floorRoute = '#/floor/view?floorId=930001&mapUrl=demo-floor-a-1f&mapId=940001&floorName=1F';
    const findView = "(() => {const find = vm => vm && (vm.handleRoomDetail && vm.floorId ? vm : (vm.$children || []).map(find).find(Boolean)); return find(document.querySelector('#app').__vue__);})()";
    const findEditor = "(() => {const find = vm => vm && (vm.place && vm.placed && vm.candidates ? vm : (vm.$children || []).map(find).find(Boolean)); return find(document.querySelector('#app').__vue__);})()";
    await evaluate('location.hash = ' + JSON.stringify(floorRoute));
    await waitPage(findView + ' && ' + findView + '.deviceList.length === 3', 'floor preview');
    await evaluate(findView + '.handleMouseDown(' + findView + '.deviceList[0], {evt: {clientX: 500, clientY: 300}})');
    assert.deepEqual(await evaluate(findView + '.roomCardPoint'), {x: 516, y: 316});
    await waitPage("Array.from(document.querySelectorAll('button')).some(button => button.textContent.includes('查看详情'))", 'room action card');
    await screenshot('01-room-action-card');
    await evaluate("Array.from(document.querySelectorAll('button')).find(button => button.textContent.includes('查看详情')).click()");
    await waitPage(findView + '.isDrawerNew', 'room detail');
    assert.ok((await evaluate('location.hash')).startsWith('#/floor/view'));
    await evaluate(findView + '.isDrawerNew = false');
    await evaluate(findView + '.handleMouseDown(' + findView + '.deviceList[0], {})');
    await evaluate("Array.from(document.querySelectorAll('button')).find(button => button.textContent.includes('进入房间')).click()");
    await waitPage("location.hash.startsWith('#/room/view')", 'room navigation');
    await screenshot('02-room-entered');
    await evaluate("location.hash = '#/floor/designer?floorId=930001&mapUrl=demo-floor-a-1f&mapId=940001&floorName=1F'");
    await waitPage(findEditor + ' && !' + findEditor + '.loading && ' + findEditor + '.placed.length === 3', 'editor loaded');
    await evaluate(findEditor + '.selectedId = 950001');
    await screenshot('06-selected-remove-icon');
    const removePoint = await evaluate('(() => {const page = ' + findEditor + ';const room = page.selected;const rect = page.$refs.canvasHost.getBoundingClientRect();return {x: rect.left + (room.x + 180) * page.ratio, y: rect.top + room.y * page.ratio};})()');
    await send('Input.dispatchMouseEvent', {type: 'mousePressed', button: 'left', clickCount: 1, ...removePoint});
    await send('Input.dispatchMouseEvent', {type: 'mouseReleased', button: 'left', clickCount: 1, ...removePoint});
    assert.equal(await evaluate(findEditor + '.candidates.some(room => room.id === 950001)'), true);
    await screenshot('03-room-removed');
    await evaluate('(() => {const page = ' + findEditor + ';const button = Array.from(document.querySelectorAll("aside > button")).find(button => button.textContent.includes("演示房间 A"));const transfer = new DataTransfer();button.dispatchEvent(new DragEvent("dragstart", {dataTransfer: transfer, bubbles: true}));const host = page.$refs.canvasHost;const rect = host.getBoundingClientRect();host.dispatchEvent(new DragEvent("drop", {dataTransfer: transfer, bubbles: true, clientX: rect.left + 700 * page.ratio, clientY: rect.top + 350 * page.ratio}));})()');
    await waitPage(findEditor + '.placed.length === 3', 'room placed again');
    // Real pointer drag on the canvas at the placed room's rectangle center.
    const pointer = await evaluate('(() => {const page = ' + findEditor + ';const rect = page.$refs.canvasHost.getBoundingClientRect();return {x: rect.left + 760 * page.ratio, y: rect.top + 370 * page.ratio, ratio: page.ratio};})()');
    await send('Input.dispatchMouseEvent', {type: 'mouseMoved', x: pointer.x, y: pointer.y});
    await send('Input.dispatchMouseEvent', {type: 'mousePressed', button: 'left', clickCount: 1, x: pointer.x, y: pointer.y});
    for (let i = 1; i <= 5; i++) await send('Input.dispatchMouseEvent', {type: 'mouseMoved', buttons: 1, x: pointer.x + i * 10, y: pointer.y + i * 4});
    await send('Input.dispatchMouseEvent', {type: 'mouseReleased', button: 'left', clickCount: 1, x: pointer.x + 50, y: pointer.y + 20});
    const position = await evaluate(findEditor + '.placed.find(room => room.id === 950001)');
    assert.ok(position.x > 710, 'pointer drag updates unscaled coordinates');
    await screenshot('04-room-dragged');
    await evaluate(findEditor + '.save()');
    await waitPage("location.hash.startsWith('#/floor/view')", 'save navigation committed');
    await evaluate('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    assert.equal(await evaluate("Array.from(document.querySelectorAll('.demo-floor-editor')).some(node => node.getBoundingClientRect().width > 0 && node.getBoundingClientRect().height > 0)"), false, 'editor hidden immediately without leave animation overlay');
    await waitPage(findView + ' && ' + findView + '.deviceList.some(room => room.id === 950001 && room.x > 710)', 'saved layout preview');
    await send('Page.reload', {ignoreCache: true});
    await waitPage(findView + ' && ' + findView + '.deviceList.some(room => room.id === 950001 && room.x > 710)', 'persisted after reload');
    await screenshot('05-layout-reloaded');
    await evaluate("location.hash = '#/floor/designer?floorId=930001&mapUrl=demo-floor-a-1f&mapId=940001&floorName=1F'");
    await waitPage(findEditor + ' && !' + findEditor + '.loading', 'editor for cancel');
    await evaluate(findEditor + '.selectedId = 950001');
    await evaluate(findEditor + '.removeSelected()');
    await evaluate(findEditor + '.exit()');
    await waitPage("!!document.querySelector('.el-message-box__btns')", 'unsaved confirmation');
    await evaluate("document.querySelector('.el-message-box__btns button').click()");
    assert.ok((await evaluate('location.hash')).includes('/floor/designer'));
    await evaluate(findEditor + '.exit()');
    await waitPage("!!document.querySelector('.el-message-box__btns')", 'confirm exit');
    await evaluate("Array.from(document.querySelectorAll('.el-message-box__btns button')).find(button => /确定|确认/.test(button.textContent)).click()");
    await waitPage(findView + ' && ' + findView + '.deviceList.some(room => room.id === 950001 && room.x > 710)', 'cancel preserves stored layout');
    const newFloorId = 930001;
`;
source = source.slice(0, start) + scenario + source.slice(end);
source = source.replace('../../docs/evidence/map-m2', '../../docs/evidence/map-m4')
  .replace("'demo-map-m2-shots'", "'demo-map-m4-shots'")
  .replace("'map-m2 browser OK;", "'map-m4 browser OK;");
new Function('require', '__dirname', source)(require, __dirname);
